def main():
    docs = []
    for path in sorted(glob.glob(f"{SRC}/*.md")):
        name = os.path.basename(path)
        title, desc = META.get(name, (name[:-3], ""))
        body = open(path).read()
        # 見出しから目次を作れるよう、h2 を拾っておく
        toc = re.findall(r"^## (.+)$", body, re.M)
        docs.append({"file": name, "title": title, "desc": desc,
                     "toc": toc, "body": body, "chars": len(body)})
        print(f"{name:28s} {len(body):6,d}字  見出し{len(toc)}個")

    with open(OUT, "w") as f:
        f.write("/* notes/*.md をアプリに埋め込んだもの。\n"
                " * 編集後は kakomon/gen_notes.py を再実行して再生成すること。\n */\n")
        f.write("window.NOTES = " + json.dumps(docs, ensure_ascii=False, indent=1) + ";\n")
    print(f"\n→ {OUT}  ({os.path.getsize(OUT):,} bytes)")


if __name__ == "__main__":
    main()
