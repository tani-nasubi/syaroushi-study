"""資料に書いた数値・主体が、法令XMLの原文と合っているかを1件ずつ照合する。

書き手（私）の記憶違いを潰すための道具。資料側の表現を正規表現で拾い、
条文側の該当箇所を漢数字を直したうえで探して、両方に同じ数が出るかを見る。
落ちたものは人が原文を読んで判断する。
"""
import os, re, ast, glob
import xml.etree.ElementTree as ET

HERE   = os.path.dirname(os.path.abspath(__file__))
NOTES  = os.path.join(os.path.dirname(HERE), "notes")
HOUREI = os.path.join(HERE, "hourei")
LAWS = ast.literal_eval(re.search(r"LAWS\s*=\s*(\{.*?\n\})",
        open(os.path.join(HERE, "gen_anaume2.py"), encoding="utf-8").read(), re.S).group(1))

KAN = {"〇":"0","零":"0","一":"1","二":"2","三":"3","四":"4","五":"5",
       "六":"6","七":"7","八":"8","九":"9"}

def k2a(s):
    """条文の漢数字を算用数字に直す。十・百・千の位取りも展開する。

    「同一額」「第一項」のような語も巻き込むので、変換前の原文とあわせて
    両方を検索対象にする（law_text が両方を連結して返す）。"""
    def conv(m):
        t = m.group(0)
        # 「〇〇〇」のような位取りのない並びは1字ずつ置き換える（表の桁区切り）
        if not set(t) & set("十百千万"):
            return "".join(KAN[c] for c in t)
        n, cur, base = 0, 0, 0
        for ch in t:
            if ch in KAN:
                cur = cur * 10 + int(KAN[ch])
            elif ch == "十":
                base += (cur or 1) * 10; cur = 0
            elif ch == "百":
                base += (cur or 1) * 100; cur = 0
            elif ch == "千":
                base += (cur or 1) * 1000; cur = 0
            elif ch == "万":
                base = (base + cur) * 10000; cur = 0
        n = base + cur
        return str(n)
    return re.sub(r"[〇零一二三四五六七八九十百千万]+", conv, s)

_txt = {}
def law_text(name):
    if name not in _txt:
        lid = next((k for k, v in LAWS.items() if v == name), None)
        p = os.path.join(HOUREI, f"{lid}.xml") if lid else None
        if not p or not os.path.exists(p):
            _txt[name] = None
        else:
            raw = re.sub(r"\s+", "", "".join(ET.parse(p).getroot().itertext()))
            raw = raw.replace(",", "").replace("，", "").replace("・", ".")
            # 漢数字を直したものと原文の両方を持たせ、どちらかに当たれば一致とみなす
            conv = k2a(raw)
            # 表の中では「一、三九〇、〇〇〇円」のように読点が桁区切りに使われる
            joined = re.sub(r"(?<=[0-9])、(?=[0-9])", "", conv)
            _txt[name] = "\n\x00\n".join([raw, conv, joined])
    return _txt[name]

