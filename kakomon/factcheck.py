def main():
    ok = ng = miss = 0
    for doc, law, label, need in CASES:
        s = DOCS.get(doc)
        if s is None:
            print(f"■ 資料が無い {doc}"); miss += 1; continue
        t = law_text(law)
        if t is None:
            print(f"― XMLが無い {law}（{label}）"); miss += 1; continue
        want = re.sub(r"\s+", "", need).replace(",", "")
        if want in t:
            ok += 1
        else:
            print(f"■ 条文に見当たらない　{doc}｜{law}｜{label}\n    探した文字列: {want[:70]}")
            ng += 1
    print(f"\n照合 {len(CASES)}件　一致 {ok} / 不一致 {ng} / 確認不能 {miss}")

if __name__ == "__main__":
    main()
