def after_trend(f, block):
    b = open(f"{N}/{f}").read()
    if block.split("\n")[0] in b: return False
    i = b.index("<!-- TREND:END -->") + len("<!-- TREND:END -->\n")
    open(f"{N}/{f}","w").write(b[:i] + "\n" + block + b[i:]); return True

def append(f, block, marker):
    b = open(f"{N}/{f}").read()
    if marker in b: return False
    open(f"{N}/{f}","a").write("\n" + block); return True

